def icone(nom, taille=18, classe=""):
    """Renvoie un <svg> en ligne (couleur heritee du texte via currentColor)."""
    return ('<svg class="ico %s" width="%d" height="%d" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%s</svg>'
            % (classe, taille, taille, LUCIDE[nom]))


def masque(nom):
    """Renvoie 'url("data:image/svg+xml,...")' utilisable comme mask-image (la couleur vient du CSS)."""
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" '
           'stroke-linecap="round" stroke-linejoin="round">%s</svg>' % LUCIDE[nom])
    return 'url("data:image/svg+xml,%s")' % quote(svg, safe="/:=' ")


def fond_champ(nom, couleur="%2394A3B8"):
    """URL data: avec trait colore (pour un background-image, ex. loupe d'un champ de recherche)."""
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="%s" stroke-width="2" '
           'stroke-linecap="round" stroke-linejoin="round">%s</svg>' % (couleur, LUCIDE[nom]))
    return 'url("data:image/svg+xml,%s")' % quote(svg, safe="/:=%' ")
